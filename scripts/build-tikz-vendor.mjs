// 重新生成 src/modules/diagram/tikzEditor/vendor/engine.bundle.js
//
// 用法：
//   TIKZ_EDITOR_SRC=/path/to/tikz-editor node scripts/build-tikz-vendor.mjs
//   （或把仓库路径作为第一个参数）
//
// 前置：本机有一份 DominikPeters/tikz-editor 的源码检出，并已安装其依赖
//       （脚本从该仓库的 node_modules 里取 esbuild / @lezer/*，不给 Zetla 增加依赖）。
//
// 产出：单个自包含 ESM bundle，导出同步渲染 + 拖拽写回所需的最小编辑 API。
//       · F1-3 只需 renderTikzToSvg；F2-1 追加 applyEditIntent / applyEdit，
//         F2-3 追加 capabilityMatrix / FEATURE_IDS（都是纯语义层，不触发文字引擎）。
//       · 不含 Computer Modern 字形轮廓数据（用户 2026-11-07 决策「先不带」）：
//         只深导入同步渲染闭包，createTexNodeTextEngine / renderTikzToSvgAsync
//         被 tree-shaking 掉，20MB text/ 字形数据自然为 0。
//       · xml-formatter 仅被 serializeSvgModelAsync(pretty) 动态 import，
//         同步路径用不到；这里用虚拟 stub 解析，避免引入额外 npm 依赖。
//       · 见 vendor/README.md 的版本与许可说明。
import { createRequire } from "node:module";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import fs from "node:fs";
import path from "node:path";

const ZETLA_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const UPSTREAM = path.resolve(process.env.TIKZ_EDITOR_SRC ?? process.argv[2] ?? "");
const CORE_SRC = path.join(UPSTREAM, "packages/core/src");
const OUT = path.join(ZETLA_ROOT, "src/modules/diagram/tikzEditor/vendor/engine.bundle.js");

if (!UPSTREAM || !fs.existsSync(path.join(CORE_SRC, "render/index.ts"))) {
  console.error(
    "找不到 tikz-editor 源码。请设置 TIKZ_EDITOR_SRC=/path/to/tikz-editor，\n" +
      "或把仓库路径作为第一个参数传入。"
  );
  process.exit(1);
}

const requireFromUpstream = createRequire(path.join(UPSTREAM, "package.json"));
let esbuildPath;
try {
  esbuildPath = requireFromUpstream.resolve("esbuild");
} catch {
  console.error("上游仓库缺 esbuild，请先在该仓库执行 npm install。");
  process.exit(1);
}
const esbuildMod = await import(pathToFileURL(esbuildPath).href);
const esbuild = esbuildMod.default ?? esbuildMod;

const version = JSON.parse(
  fs.readFileSync(path.join(UPSTREAM, "packages/core/package.json"), "utf8")
).version;
let commit = "unknown";
try {
  commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: UPSTREAM, encoding: "utf8" }).trim();
} catch {
  // 非 git 检出的源码包：版本仍写在 banner，commit 标 unknown。
}

// monorepo 内的 workspace 包名 → 源码入口
const WORKSPACE = {
  "@tikz-editor/lezer-tex": "packages/lezer-tex/src/index.ts",
  "@tikz-editor/lezer-tikz": "packages/lezer-tikz/src/index.ts",
  "@tikz-editor/lang-tikz": "packages/lang-tikz/src/index.ts",
};

const vendorPlugin = {
  name: "zetla-tikz-vendor",
  setup(build) {
    build.onResolve({ filter: /.*/ }, (args) => {
      if (args.path === "xml-formatter") {
        return { path: "xml-formatter", namespace: "zetla-stub" };
      }
      const ws = WORKSPACE[args.path];
      if (ws) return { path: path.join(UPSTREAM, ws) };
      if (!args.path.startsWith(".")) return undefined; // 交给 esbuild 从上游 node_modules 解析
      // 上游用 NodeNext 风格：源码里写 "./foo.js"，磁盘上其实是 "./foo.ts"
      const base = path.resolve(path.dirname(args.importer || path.join(CORE_SRC, "entry.ts")), args.path);
      const stripped = base.endsWith(".js") ? base.slice(0, -3) : base;
      for (const candidate of [
        stripped + ".ts",
        stripped + ".tsx",
        path.join(stripped, "index.ts"),
      ]) {
        if (fs.existsSync(candidate)) return { path: candidate };
      }
      return undefined;
    });
    build.onLoad({ filter: /.*/, namespace: "zetla-stub" }, () => ({
      contents: "export default function xmlFormatter(input) { return input; }",
      loader: "js",
    }));
  },
};

const result = await esbuild.build({
  stdin: {
    // 不导出 createTexNodeTextEngine —— 这是「不带 20MB 字形数据」的关键。
    // 编辑 API 走同一份 parse/semantic 闭包，tree-shaking 后增量很小。
    contents: [
      'export { renderTikzToSvg } from "./render/index.js";',
      'export { applyEditIntent, applyEdit } from "./edit/apply.js";',
      'export { capabilityMatrix, FEATURE_IDS } from "./capabilities/index.js";',
    ].join("\n"),
    resolveDir: CORE_SRC,
    sourcefile: path.join(CORE_SRC, "__zetla_vendor_entry.ts"),
    loader: "ts",
  },
  outfile: OUT,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  treeShaking: true,
  plugins: [vendorPlugin],
  metafile: true,
  logLevel: "warning",
  legalComments: "none",
  banner: {
    js:
      `/*! @tikz-editor/core v${version} · MIT (Dominik Peters) · commit ${commit}\n` +
      ` * Generated by scripts/build-tikz-vendor.mjs — DO NOT EDIT.\n` +
      ` * License: see LICENSE in this directory. Glyph-outline data intentionally excluded.\n` +
      ` */`,
  },
});

const bytes = fs.statSync(OUT).size;
const inputs = Object.entries(result.metafile?.inputs ?? {});
const glyphBytes = inputs
  .filter(([f]) => /text\/.*(fonts|outlines|generated)|fonts\/data/i.test(f))
  .reduce((sum, [, v]) => sum + (v.bytesInOutput ?? 0), 0);
const markup = fs.readFileSync(OUT, "utf8");
const leftoverImports = /^import\s|^\s*import\s*\(/m.test(markup.slice(0, 4096));

console.log(`bundle      : ${(bytes / 1024 / 1024).toFixed(2)} MB`);
console.log(`input files : ${inputs.length}`);
console.log(`glyph bytes : ${glyphBytes} (期望 0)`);
console.log(`self-contained: ${!leftoverImports} (期望 true)`);
console.log(`version     : ${version} @ ${commit}`);
if (glyphBytes > 0 || leftoverImports) {
  console.error("vendoring 校验失败：字形数据被打包或存在未解析的外部 import。");
  process.exit(1);
}
