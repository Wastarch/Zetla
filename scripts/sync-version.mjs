#!/usr/bin/env node
/**
 * Zetla · 版本号统一同步脚本
 *
 * 唯一版本源：package.json 的 version 字段——只改这一处，全项目版本号一起切换。
 * 同步落点：
 *   - src-tauri/tauri.conf.json   Tauri 应用版本（关于页 getVersion()、安装包名均读它）
 *   - src-tauri/Cargo.toml        Rust crate 版本
 *   - src-tauri/Cargo.lock        zetla 条目版本（与 Cargo.toml 对齐）
 *   - package-lock.json           npm 锁文件根版本
 *   - src/version.ts              前端常量 APP_VERSION（生成文件，勿手改）
 *
 * 用法：
 *   node scripts/sync-version.mjs            按 package.json 当前版本同步（幂等）
 *   node scripts/sync-version.mjs 0.2.0      先把 package.json 改成 0.2.0，再全量同步
 *
 * npm run dev / build / tauri 已自动前置本脚本；也可手动 npm run version:sync。
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const PATHS = {
  pkg: path.join(root, "package.json"),
  pkgLock: path.join(root, "package-lock.json"),
  tauriConf: path.join(root, "src-tauri", "tauri.conf.json"),
  cargoToml: path.join(root, "src-tauri", "Cargo.toml"),
  cargoLock: path.join(root, "src-tauri", "Cargo.lock"),
  versionTs: path.join(root, "src", "version.ts"),
};

/** x.y.z，允许 -prerelease / +build 后缀 */
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

function fail(message) {
  console.error(`\n[sync-version] ${message}\n`);
  process.exit(1);
}

function readText(file) {
  if (!existsSync(file)) fail(`找不到文件：${file}`);
  return readFileSync(file, "utf8");
}

/** 内容一致就不落盘（幂等，避免污染 git diff / mtime）。返回是否有改动。 */
function writeIfChanged(file, next) {
  const prev = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (prev === next) return false;
  writeFileSync(file, next);
  return true;
}

/** 统一换行符并补结尾换行；eol 取目标文件原有风格（本仓库工作区为 CRLF）。 */
function withEol(text, eol) {
  return text.replace(/\r?\n/g, eol) + eol;
}

function detectEol(text) {
  return /\r\n/.test(text) ? "\r\n" : "\n";
}

function readJson(file) {
  try {
    return JSON.parse(readText(file));
  } catch (error) {
    fail(`解析 ${file} 失败：${error.message}`);
  }
}

/** 把 version 写进 package.json（唯一版本源）。 */
function setPkgVersion(version) {
  const file = PATHS.pkg;
  const pkg = readJson(file);
  if (pkg.version === version) return;
  pkg.version = version;
  writeIfChanged(file, withEol(JSON.stringify(pkg, null, 2), detectEol(readText(file))));
}

function syncTauriConf(version) {
  const file = PATHS.tauriConf;
  const conf = readJson(file);
  const from = conf.version;
  if (from === version) return `已是 ${version}`;
  conf.version = version;
  writeIfChanged(file, withEol(JSON.stringify(conf, null, 4), detectEol(readText(file))));
  return `${from} → ${version}`;
}

function syncCargoToml(version) {
  const file = PATHS.cargoToml;
  const text = readText(file);
  // [package] 是第一个节，其 version 行为文件中首个 version 赋值
  const re = /^(\[package\][\s\S]*?^version = ")([^"]*)(")/m;
  const match = text.match(re);
  if (!match) fail(`${file} 的 [package] 节缺少 version 字段`);
  const from = match[2];
  if (from === version) return `已是 ${version}`;
  const next = text.replace(re, (_all, head, _old, tail) => head + version + tail);
  writeIfChanged(file, next);
  return `${from} → ${version}`;
}

function syncCargoLock(version) {
  const file = PATHS.cargoLock;
  const text = readText(file);
  const re = /(name = "zetla"\r?\nversion = ")[^"]*(")/;
  const match = text.match(re);
  if (!match) return "跳过（锁文件中无 zetla 条目）";
  if (match[0].includes(`version = "${version}"`)) return `已是 ${version}`;
  writeIfChanged(file, text.replace(re, `$1${version}$2`));
  return `→ ${version}`;
}

function syncPkgLock(version) {
  const file = PATHS.pkgLock;
  const lock = readJson(file);
  let changed = false;
  if (lock.version !== version) {
    lock.version = version;
    changed = true;
  }
  if (lock.packages && lock.packages[""] && lock.packages[""].version !== version) {
    lock.packages[""].version = version;
    changed = true;
  }
  if (!changed) return `已是 ${version}`;
  writeIfChanged(file, withEol(JSON.stringify(lock, null, 2), detectEol(readText(file))));
  return `→ ${version}`;
}

function syncVersionTs(version) {
  const file = PATHS.versionTs;
  const content = withEol(
    [
      "// AUTO-GENERATED by scripts/sync-version.mjs — 请勿手动修改。",
      "// 版本唯一源：package.json 的 version 字段。",
      "// 升级版本：改 package.json 后执行 npm run version:sync（dev/build/tauri 会自动同步）。",
      `export const APP_VERSION = "${version}";`,
      "",
    ].join("\n"),
    "\r\n",
  );
  if (!writeIfChanged(file, content)) return `已是 ${version}`;
  return `生成 APP_VERSION = ${version}`;
}

// ---------- 主流程 ----------

const arg = process.argv[2];
if (arg) {
  if (arg.startsWith("-")) {
    fail(`未知参数：${arg}\n用法：node scripts/sync-version.mjs [新版本号]，如 0.2.0`);
  }
  if (!SEMVER.test(arg)) {
    fail(`版本号格式不正确：${arg}（应为 x.y.z，可带 -prerelease 后缀）`);
  }
  setPkgVersion(arg);
}

const version = readJson(PATHS.pkg).version;
if (!version) fail("package.json 缺少 version 字段");
if (!SEMVER.test(version)) fail(`package.json version 格式不正确：${version}`);

console.log(`[sync-version] 唯一版本源：package.json → ${version}`);
const rows = [
  ["package.json", arg ? `已设为 ${version}` : `已是 ${version}`],
  ["src-tauri/tauri.conf.json", syncTauriConf(version)],
  ["src-tauri/Cargo.toml", syncCargoToml(version)],
  ["src-tauri/Cargo.lock", syncCargoLock(version)],
  ["package-lock.json", syncPkgLock(version)],
  ["src/version.ts", syncVersionTs(version)],
];
const width = Math.max(...rows.map(([name]) => name.length));
for (const [name, status] of rows) {
  console.log(`  ${name.padEnd(width)}  ${status}`);
}
